//! Create-path orchestration with scheduler placement and stale-operation safety.
//!
//! Composes policy, quota, regional and cell scheduling, metadata commit,
//! and audit emission into one control-plane create path. Retries converge
//! to a single outcome through idempotency-key dedup and operation-identity
//! checks instead of double-applying.
//!
//! The orchestrator is synchronous and holds no async guards. Audit emission
//! stays best-effort: a saturated sink never fails placement or create.

